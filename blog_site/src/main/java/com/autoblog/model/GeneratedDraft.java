package com.autoblog.model;

import java.time.LocalDateTime;

public class GeneratedDraft {
    private long id;
    private long siteId;
    private String siteName;
    private String keyword;
    private String title;
    private String slug;
    private String excerpt;
    private String contentHtml;
    private String tags;
    private String categories;
    private Long wordpressCategoryId;
    private int verificationScore;
    private boolean approved;
    private String issues;
    private int promptTokens;
    private int completionTokens;
    private int totalTokens;
    private String officialImages;
    private String status;
    private LocalDateTime createdAt;
    private LocalDateTime updatedAt;

    public long getId() { return id; }
    public void setId(long id) { this.id = id; }
    public long getSiteId() { return siteId; }
    public void setSiteId(long siteId) { this.siteId = siteId; }
    public String getSiteName() { return siteName; }
    public void setSiteName(String siteName) { this.siteName = siteName; }
    public String getKeyword() { return keyword; }
    public void setKeyword(String keyword) { this.keyword = keyword; }
    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }
    public String getSlug() { return slug; }
    public void setSlug(String slug) { this.slug = slug; }
    public String getExcerpt() { return excerpt; }
    public void setExcerpt(String excerpt) { this.excerpt = excerpt; }
    public String getContentHtml() { return contentHtml; }
    public void setContentHtml(String contentHtml) { this.contentHtml = contentHtml; }
    public String getTags() { return tags; }
    public void setTags(String tags) { this.tags = tags; }
    public String getCategories() { return categories; }
    public void setCategories(String categories) { this.categories = categories; }
    public Long getWordpressCategoryId() { return wordpressCategoryId; }
    public void setWordpressCategoryId(Long wordpressCategoryId) { this.wordpressCategoryId = wordpressCategoryId; }
    public int getVerificationScore() { return verificationScore; }
    public void setVerificationScore(int verificationScore) { this.verificationScore = verificationScore; }
    public boolean isApproved() { return approved; }
    public void setApproved(boolean approved) { this.approved = approved; }
    public String getIssues() { return issues; }
    public void setIssues(String issues) { this.issues = issues; }
    public int getPromptTokens() { return promptTokens; }
    public void setPromptTokens(int promptTokens) { this.promptTokens = promptTokens; }
    public int getCompletionTokens() { return completionTokens; }
    public void setCompletionTokens(int completionTokens) { this.completionTokens = completionTokens; }
    public int getTotalTokens() { return totalTokens; }
    public void setTotalTokens(int totalTokens) { this.totalTokens = totalTokens; }
    public String getOfficialImages() { return officialImages; }
    public void setOfficialImages(String officialImages) { this.officialImages = officialImages; }
    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }
    public LocalDateTime getCreatedAt() { return createdAt; }
    public void setCreatedAt(LocalDateTime createdAt) { this.createdAt = createdAt; }
    public LocalDateTime getUpdatedAt() { return updatedAt; }
    public void setUpdatedAt(LocalDateTime updatedAt) { this.updatedAt = updatedAt; }
}
